// Both fixture creation and mutation may be asynchronous in an isolated SQL
// adapter. Each scenario owns and closes every harness, also after assertions.
for (const scenario of CASES) {
  const check = scenario.run;
  scenario.run = async createHarness => {
    const opened = [];
    try { return await check(async options => { const h = await createHarness(options); opened.push(h); return h; }); }
    finally { for (const h of opened.reverse()) await h.close(); }
  };
}
