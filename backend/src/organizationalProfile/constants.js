'use strict';

function frozen(values) {
  return Object.freeze([...values]);
}

const CONTRACT_VERSION = 1;
const KNOWLEDGE_STATUSES = frozen(['KNOWN', 'UNKNOWN', 'NONE', 'NOT_APPLICABLE']);
const VERIFICATION_STATUSES = frozen(['NOT_REQUIRED', 'UNVERIFIED', 'VERIFIED', 'DISPUTED', 'REVOKED', 'EXPIRED']);
const CONFLICT_STATUSES = frozen(['CLEAR', 'CONFLICTED']);
const EDITORIAL_LIFECYCLE_STATUSES = frozen(['DRAFT', 'APPROVED', 'PUBLISHED', 'SUPERSEDED', 'ARCHIVED']);
const PROJECTION_STATUSES = frozen(['DISCLOSED', 'WITHHELD']);
const CONFIDENTIALITY_CLASSES = frozen(['INTERNAL', 'RESTRICTED', 'HIGHLY_RESTRICTED']);
const PROJECTION_MODES = frozen(['EXACT', 'DERIVED', 'REDACTED', 'OMITTED']);
const COMPLETION_RESULTS = frozen(['COMPLETE', 'INCOMPLETE']);
const PROFILE_SCOPE_TYPES = frozen(['ORGANIZATION', 'UNIT', 'TEAM']);
const CONSTRAINT_TYPES = frozen(['PROHIBITED', 'UNAVAILABLE']);
const TAXONOMY_SCHEMES = frozen(['THEMATIC_AREA', 'STRATEGIC_PRIORITY']);
const TERRITORY_SCHEMES = frozen(['COUNTRY_TERRITORY', 'ADMINISTRATIVE_AREA', 'STATISTICAL_REGION', 'TRANSNATIONAL_AREA']);
const INSTITUTIONAL_SCHEMES = frozen(['LEGAL_NATURE', 'INSTITUTION_TYPE', 'CONTROL_STATUS', 'NON_PROFIT_STATUS', 'ECONOMIC_SIZE_CLASS']);
const POPULATION_SCHEMES = frozen(['SERVED_POPULATION_GROUP']);
const ALL_SCHEMES = frozen([...TAXONOMY_SCHEMES, ...TERRITORY_SCHEMES, ...INSTITUTIONAL_SCHEMES, ...POPULATION_SCHEMES]);
const THEMATIC_EXTERNAL_MAPPING_RELATIONS = frozen(['EXACT', 'CLOSE', 'BROADER', 'NARROWER']);
const TERRITORY_EXTERNAL_MAPPING_RELATIONS = frozen([...THEMATIC_EXTERNAL_MAPPING_RELATIONS, 'OVERLAPS']);
const EXTERNAL_MAPPING_RELATIONS_BY_SCHEME = Object.freeze({
  THEMATIC_AREA: THEMATIC_EXTERNAL_MAPPING_RELATIONS,
  STRATEGIC_PRIORITY: THEMATIC_EXTERNAL_MAPPING_RELATIONS,
  COUNTRY_TERRITORY: TERRITORY_EXTERNAL_MAPPING_RELATIONS,
  ADMINISTRATIVE_AREA: TERRITORY_EXTERNAL_MAPPING_RELATIONS,
  STATISTICAL_REGION: TERRITORY_EXTERNAL_MAPPING_RELATIONS,
  TRANSNATIONAL_AREA: TERRITORY_EXTERNAL_MAPPING_RELATIONS
});
const TERRITORY_RELATIONS = frozen(['OPERATIONAL_PRESENCE', 'DELIVERY_CAPABILITY', 'DEMONSTRATED_EXPERIENCE', 'STRATEGIC_PRIORITY']);
const SERVED_POPULATION_RELATIONS = frozen(['SERVES', 'STRATEGIC_PRIORITY']);

function isExternalMappingRelationAllowed(schemeId, relation) {
  if (typeof schemeId !== 'string' || typeof relation !== 'string'
      || !Object.hasOwn(EXTERNAL_MAPPING_RELATIONS_BY_SCHEME, schemeId)) return false;
  return EXTERNAL_MAPPING_RELATIONS_BY_SCHEME[schemeId].includes(relation);
}

module.exports = {
  ALL_SCHEMES,
  COMPLETION_RESULTS,
  CONFIDENTIALITY_CLASSES,
  CONFLICT_STATUSES,
  CONSTRAINT_TYPES,
  CONTRACT_VERSION,
  EDITORIAL_LIFECYCLE_STATUSES,
  EXTERNAL_MAPPING_RELATIONS_BY_SCHEME,
  INSTITUTIONAL_SCHEMES,
  KNOWLEDGE_STATUSES,
  POPULATION_SCHEMES,
  PROFILE_SCOPE_TYPES,
  PROJECTION_MODES,
  PROJECTION_STATUSES,
  SERVED_POPULATION_RELATIONS,
  TAXONOMY_SCHEMES,
  TERRITORY_RELATIONS,
  TERRITORY_SCHEMES,
  VERIFICATION_STATUSES,
  isExternalMappingRelationAllowed
};
