function sameList(left, right) {
  return Array.isArray(left) && left.length === right.length && left.every((value, index) => value === right[index]);
}

function validateEventCatalog(entries = EVENTS) {
  if (!Array.isArray(entries) || !Object.isFrozen(entries) || entries.length !== 146) throw new TypeError('Event catalog must contain exactly 146 frozen entries.');
  const seen = new Set();
  for (const entry of entries) {
    const keys = ['code', 'eventVersion', 'auditClass', 'residencyRule', 'actorTypes', 'payloadFields', 'maxPayloadBytes', 'maxEventBytes'];
    if (!entry || !Object.isFrozen(entry) || Reflect.ownKeys(entry).length !== keys.length || keys.some(key => !Object.hasOwn(entry, key))
      || !/^[A-Z][A-Z0-9_]{0,63}$/.test(entry.code) || entry.code.includes('*') || seen.has(entry.code)
      || entry.eventVersion !== EVENT_VERSION || !Object.values(AUDIT_CLASSES).includes(entry.auditClass)
      || !['CENTRAL_AUTHORITY', 'TENANT_AUTHORITY', 'OPERATION_AUTHORITY'].includes(entry.residencyRule)
      || !Object.isFrozen(entry.actorTypes) || !Object.isFrozen(entry.payloadFields)
      || entry.maxPayloadBytes !== 8192 || entry.maxEventBytes !== 16384) throw new TypeError('F7 event catalog entry is invalid.');
    const approved = byCode.get(entry.code);
    if (!approved || entry.eventVersion !== approved.eventVersion || entry.auditClass !== approved.auditClass
      || entry.residencyRule !== approved.residencyRule || !sameList(entry.actorTypes, approved.actorTypes)
      || !sameList(entry.payloadFields, approved.payloadFields)) throw new TypeError('F7 event catalog differs from the approved contract.');
    seen.add(entry.code);
  }
  return true;
}

function resolveEvent(code, version = EVENT_VERSION) {
  const entry = typeof code === 'string' ? byCode.get(code) : null;
  return entry && version === EVENT_VERSION ? entry : null;
}

function resolveResidence(entry, trustedContext) {
  if (!entry || !trustedContext || !['CENTRAL', 'TENANT'].includes(trustedContext.operationAuthority)) throw new TypeError('Audit residence context is invalid.');
  const location = entry.residencyRule === 'CENTRAL_AUTHORITY' ? 'CENTRAL'
    : entry.residencyRule === 'TENANT_AUTHORITY' ? 'TENANT' : trustedContext.operationAuthority;
  if (location === 'TENANT' && typeof trustedContext.tenantId !== 'string') throw new TypeError('Tenant audit event requires a trusted tenant.');
  return location;
}

