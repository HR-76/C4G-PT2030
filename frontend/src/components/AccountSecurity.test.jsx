import React from 'react'
import { afterEach, it, expect, vi } from 'vitest'
import { render, screen, cleanup, fireEvent, waitFor } from '@testing-library/react'
import AccountSecurity from '../pages/AccountSecurity'
const load = vi.hoisted(() => vi.fn())
const change = vi.hoisted(() => vi.fn())
vi.mock('../api/api', () => ({ authApi: { accountSecurity: load, emailVerification: change } }))
afterEach(cleanup)
it('does not invent an email preference or activation without an IdP component', async () => {
  load.mockResolvedValue({ data: { mfaOptional: true } })
  render(<AccountSecurity />)
  expect(await screen.findByRole('heading', { name: 'Verificação adicional por email' })).toBeTruthy()
  expect(screen.getByRole('status').textContent).toContain('Por configurar neste ambiente')
  const unavailable = screen.getByRole('button', { name: 'Ativar verificação por email' })
  expect(unavailable.disabled).toBe(true)
  change.mockClear()
  fireEvent.click(unavailable)
  expect(change).not.toHaveBeenCalled()
  expect(screen.getByRole('link', { name: 'Gerir aplicação autenticadora' }).getAttribute('href')).toBe('/api/auth/account')
  expect(screen.queryByRole('switch')).toBeNull()
  expect(screen.queryByRole('checkbox')).toBeNull()
  expect(screen.queryByText(/Podes adicionar uma aplicação autenticadora/)).toBeNull()
  expect(screen.queryByText(/A alteração é feita nas definições/)).toBeNull()
  fireEvent.click(screen.getByText('Como funciona?', { selector: 'summary' }))
  expect(screen.getByRole('link', { name: 'Gerir segurança no fornecedor de identidade' }).getAttribute('href')).toBe('/api/auth/account')
  expect(screen.getByText(/métodos de autenticação já configurados/)).toBeTruthy()
})
it.each([false, true])('uses confirmed state and starts only the matching protected action (%s)', async enabled => {
  load.mockResolvedValue({ data: { mfaOptional: true, emailVerification: { available: true, enabled } } })
  change.mockRejectedValue(new Error('provider unavailable'))
  render(<AccountSecurity />)
  const button = await screen.findByRole('button', { name: enabled ? 'Desativar verificação por email' : 'Ativar verificação por email' })
  fireEvent.click(button)
  await waitFor(() => expect(change).toHaveBeenCalledWith(enabled ? 'disable' : 'enable'))
  expect(await screen.findByRole('alert')).toBeTruthy()
  expect(screen.getByRole('status').textContent).toBe(enabled ? 'Ativa' : 'Desativada')
})
it('expired account token requires explicit login instead of assuming disabled or looping', async () => {
  load.mockRejectedValue({ response: { data: { code: 'ACCOUNT_REAUTH_REQUIRED' } } })
  render(<AccountSecurity />)
  expect(await screen.findByRole('link', { name: 'Confirmar sessão' })).toBeTruthy()
  expect(screen.queryByRole('button')).toBeNull()
})
it('preserves enhanced authentication outside documentary review', async () => {
  load.mockResolvedValue({ data: { mfaOptional: false } })
  render(<AccountSecurity />)
  expect(await screen.findByText(/operações fora da revisão documental/)).toBeTruthy()
  expect(screen.getByText(/sem exigir um código adicional para decidir/)).toBeTruthy()
  expect(screen.queryByText('Opcional')).toBeNull()
})
it('does not invent security state when settings fail to load', async () => {
  load.mockRejectedValue(new Error('unavailable'))
  render(<AccountSecurity />)
  expect(await screen.findByRole('alert')).toBeTruthy()
  expect(screen.queryByRole('link')).toBeNull()
})

it('keeps native security management accessible when email consultation expires', async () => {
  load.mockResolvedValue({ data: { mfaOptional: true, emailVerification: { available: false, reauthenticationRequired: true } } })
  render(<AccountSecurity />)
  const confirm = await screen.findByRole('link', { name: 'Confirmar sessão' })
  expect(confirm.getAttribute('href')).toBe('/api/auth/oidc/login?returnTo=%2Fconta%2Fseguranca')
  expect(screen.getByRole('link', { name: 'Gerir aplicação autenticadora' })).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'Ativar verificação por email' })).toBeNull()
  expect(screen.queryByText('Desativada')).toBeNull()
  expect(screen.queryByText(/Por configurar neste ambiente/)).toBeNull()
})

it('shows provider consultation rather than inventing password or authenticator status', async () => {
  load.mockResolvedValue({ data: { mfaOptional: true, emailVerification: {available:true,enabled:false} } })
  render(<AccountSecurity />)
  await screen.findByRole('heading',{name:'Palavra-passe'})
  expect(screen.getAllByText('Consultar no fornecedor')).toHaveLength(2)
  expect(screen.getByRole('link',{name:'Gerir palavra-passe'}).getAttribute('href')).toBe('/api/auth/account')
  expect(screen.queryByText('Ativa')).toBeNull()
})
